/**
 * Segmented: a small labelled button group (Heatmap | Bars, Linear |
 * Compressed, Both | Income | Expenses, Summary | Detailed). The pressed
 * button carries `aria-pressed="true"`.
 */
export function Segmented<T extends string>({
  label,
  value,
  options,
  onChange,
}: {
  label: string;
  value: T;
  options: readonly { value: T; label: string }[];
  onChange: (v: T) => void;
}) {
  return (
    <div className="chart-seg" role="group" aria-label={label}>
      {options.map((o) => (
        <button key={o.value} type="button" aria-pressed={value === o.value} onClick={() => onChange(o.value)}>
          {o.label}
        </button>
      ))}
    </div>
  );
}
